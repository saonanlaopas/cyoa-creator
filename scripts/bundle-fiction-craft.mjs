import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
const root = new URL('../', import.meta.url);
const text = readFileSync(new URL('docs/writing/FICTION_CRAFT.md', root), 'utf8');
const catalog = JSON.parse(readFileSync(new URL('docs/writing/fiction-craft-versions.json', root), 'utf8'));
const sha256 = createHash('sha256').update(text).digest('hex');
if (catalog.id !== 'cyoa.fiction-craft' || catalog.versions[catalog.currentVersion] !== sha256
  || !text.includes(`Version: ${catalog.currentVersion} `) || text.includes('\r')) throw new Error('fiction_craft_source_version_or_digest_invalid');
const target = new URL('packages/domain/src/generated/fiction-craft.ts', root);
const generated = '// Generated by scripts/bundle-fiction-craft.mjs; edit docs/writing/FICTION_CRAFT.md, never this copy.\n'
  + `export const fictionCraftReleaseDigests: Readonly<Record<string, string>> = ${JSON.stringify(catalog.versions)};\n`
  + `export const packagedFictionCraft = ${JSON.stringify({ schemaVersion: 1, id: catalog.id, version: catalog.currentVersion, sha256, text })} as const;\n`;
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== generated) throw new Error('fiction_craft_bundle_stale_run_node_scripts_bundle-fiction-craft.mjs');
} else writeFileSync(target, generated);
